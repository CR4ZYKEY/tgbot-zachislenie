// Общая эвристика "этот ответ — затруднение?" — используется и в скрипте
// npm run stats, и в Google-таблице: статус «Нужна помощь» на вкладке
// "Родители", пометка в "Ответах", проблемные вопросы в "Статистике".
// Один источник правды, чтобы цифры в консоли и в таблице не расходились.
//
// Только ответы «что-то не получается»: «Там пусто», «Не подходит пароль»,
// «Не понимаю…», «Не нашёл», «Не хватает документа», «Инструкции нет»,
// «Незачёт». Обычные «Нет / Ещё нет / Позже / Ещё не знаем» сюда не входят —
// это нормальный ход пути, а не просьба о помощи.
export const FRICTION_MARKERS = ['.empty', '.password', '.confused', '.notfound', '.unclear', '.missing', '.noinstr', '.fail'];

export function isFrictionAnswer(value: string): boolean {
  return FRICTION_MARKERS.some((m) => value.includes(m));
}
